const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { app, Menu } = require('electron');
const dir = fs.mkdtempSync(path.join(process.env.TMPDIR || app.getPath('temp'), 'mdview-shortcuts-'));
app.setPath('userData', path.join(dir, 'profile'));
app.disableHardwareAcceleration();
app.on('browser-window-created', (_event, win) => { win.setOpacity(0); win.setSkipTaskbar(true); win.webContents.setBackgroundThrottling(false); });
(async () => {
  const { win } = await require('../src/main.cjs');
  const run = code => win.webContents.executeJavaScript(code, true);
  const wait = async code => { for (let i = 0; i < 240; i++) { if (await run(code)) return; await new Promise(resolve => setTimeout(resolve, 25)); } assert.fail(code); };
  const key = (keyCode, modifiers = []) => { win.webContents.sendInputEvent({ type: 'keyDown', keyCode, modifiers }); win.webContents.sendInputEvent({ type: 'keyUp', keyCode, modifiers }); };
  await wait('!!currentDocument && !restoringView');
  win.show(); win.focus();

  key('F1');
  await wait('!!document.querySelector("#shortcuts-dialog")?.open');
  assert.equal(await run('document.activeElement.id'), 'shortcuts-filter');
  key('Escape');
  await wait('!document.querySelector("#shortcuts-dialog").open');
  const item = Menu.getApplicationMenu().getMenuItemById('keyboard-shortcuts');
  assert.ok(item, 'visible native View menu item');
  const viewMenu = Menu.getApplicationMenu().items[2].submenu;
  assert.ok(viewMenu.items.includes(item));
  const pendingPopup = run('window.mdview.popupMenu(2,{x:80,y:30})');
  await new Promise(resolve=>setTimeout(resolve,100));
  viewMenu.closePopup(win); await pendingPopup;
  item.click();
  await wait('document.querySelector("#shortcuts-dialog").open');
  await run('document.querySelector("#shortcuts-close").click()');
  await wait('!document.querySelector("#shortcuts-dialog").open');
  // Focus restoration, filtering, localization, and modal isolation in the actual app.
  await run('toggleEditing(); richEditor.editor.view.focus()');
  await wait('editing && document.activeElement.matches(".ProseMirror")');
  await run('richEditor.editor.commands.insertContent("shortcut-history-sentinel "); richEditor.editor.view.focus()');
  const source = await run('payload().source');
  const model = await run('JSON.stringify(richEditor.editor.getJSON())');
  const selection = await run('JSON.stringify(richEditor.editor.state.selection.toJSON())');
  const docId = await run('currentDocument.id');
  await wait('window.mdview.getMenuBar().then(data => data.state.shortcutHelpOpen === false)');
  win.focus();
  key('F1'); await wait('document.querySelector("#shortcuts-dialog").open');
  await wait('(window.mdview.getMenuBar().then(data => data.state.shortcutHelpOpen))');
  const filter = async value => run(`document.querySelector('#shortcuts-filter').value=${JSON.stringify(value)}; document.querySelector('#shortcuts-filter').dispatchEvent(new Event('input'))`);
  await filter('两个空格');
  assert.deepEqual(await run('[...document.querySelectorAll(".shortcut-row")].map(n=>n.dataset.shortcut)'), ['code-indent']);
  await filter('<img src=x>');
  assert.equal(await run('document.querySelectorAll(".shortcut-row").length'), 0);
  assert.equal(await run('document.querySelectorAll("#shortcuts-dialog img").length'), 0);
  await filter('');
  await run('document.querySelector("#shortcuts-filter").focus()');
  win.webContents.insertText('Ctrl+Shift+F');
  await wait('document.querySelectorAll(".shortcut-row").length===1');
  assert.equal(await run('document.querySelector(".shortcut-row").dataset.shortcut'),'find-all');
  await filter('');
  key('Tab'); await wait('document.activeElement.id === "shortcuts-results"');
  key('Tab'); await wait('document.activeElement.id === "shortcuts-close"');
  key('Tab',['shift']); await wait('document.activeElement.id === "shortcuts-results"');
  for (let i=0;i<12;i++) key('Tab');
  assert.equal(await run('document.querySelector("#shortcuts-dialog").contains(document.activeElement)'), true);
  for (const [code, modifiers] of [['N',['control']], ['W',['control']], ['E',['control']], [',',['control']], ['F',['control']], ['F11',[]], ['F10',[]], ['Tab',['control']]]) key(code,modifiers);
  await new Promise(resolve=>setTimeout(resolve,150));
  assert.equal(await run('currentDocument.id'), docId);
  assert.equal(await run('editing'), true);
  assert.equal(await run('document.querySelectorAll("dialog[open]").length'), 1);
  assert.equal(win.isFullScreen(), false);
  // A queued native-menu invocation must not replace/stack the help dialog.
  Menu.getApplicationMenu().items[3].submenu.items[0].click();
  await new Promise(resolve=>setTimeout(resolve,100));
  assert.equal(await run('document.querySelector("#settings-dialog").open'), false);
  const font = await run('fontSize');
  await run('document.querySelector("#shortcuts-filter").dispatchEvent(new WheelEvent("wheel",{bubbles:true,ctrlKey:true,deltaY:-100,cancelable:true}))');
  assert.equal(await run('fontSize'), font);
  assert.equal(await run('payload().source'), source);
  assert.equal(await run('JSON.stringify(richEditor.editor.getJSON())'), model);
  assert.equal(await run('JSON.stringify(richEditor.editor.state.selection.toJSON())'), selection);
  await run('window.shortcutLeakedKeys=0; window.shortcutCapture=e=>{window.shortcutLeakedKeys++; e.preventDefault(); e.stopImmediatePropagation()}; document.addEventListener("keydown",window.shortcutCapture,true)');
  key('Escape'); await wait('!document.querySelector("#shortcuts-dialog").open && document.activeElement.matches(".ProseMirror")');
  assert.equal(await run('window.shortcutLeakedKeys'),0,'help keyboard handling precedes editor context-menu capture listeners');
  await run('document.removeEventListener("keydown",window.shortcutCapture,true)');
  await run('richEditor.editor.commands.undo()');
  assert.ok(!(await run('payload().source')).includes('shortcut-history-sentinel'), 'help creates no undo step');
  await run('richEditor.editor.commands.redo()'); assert.equal(await run('payload().source'), source);
  // Other dialogs retain priority, especially an outstanding unsaved decision.
  await run('openSettings()'); key('F1'); await new Promise(resolve=>setTimeout(resolve,100));
  assert.equal(await run('document.querySelector("#shortcuts-dialog").open'), false);
  await run('document.querySelector("#settings-dialog").close()');
  await run('openCodeDialog(document.querySelector("#editor-content .expand-code"))');
  key('F1'); await new Promise(resolve=>setTimeout(resolve,100));
  assert.equal(await run('document.querySelector("#shortcuts-dialog").open'),false);
  assert.equal(await run('codeDialog.open'),true);
  await run('codeDialog.close()');
  await run('void closeTab(currentDocument.id)');
  await wait('document.querySelector("#unsaved-dialog").open');
  key('F1'); item.click(); await new Promise(resolve=>setTimeout(resolve,100));
  assert.equal(await run('document.querySelector("#shortcuts-dialog").open'), false);
  assert.equal(await run('document.querySelector("#unsaved-dialog").open'), true);
  key('Escape'); await wait('!fileBusy && !document.querySelector("#unsaved-dialog").open');
  assert.equal(await run('payload().source'), source);
  const colors = new Set();
  win.setMinimumSize(320,300); win.setSize(420,560);
  for (const language of ['en','zh-CN','en']) {
    await run(`window.mdview.setLanguage(${JSON.stringify(language)})`);
    await wait('window.mdview.getMenuBar().then(data => data.state.shortcutHelpOpen === false)');
    win.focus();
    key('F1'); await wait('document.querySelector("#shortcuts-dialog").open');
    await wait(`document.querySelector('#shortcuts-title').textContent === ${JSON.stringify(language==='en'?'Keyboard shortcuts':'快捷键速查')}`);
    assert.equal(Menu.getApplicationMenu().getMenuItemById('keyboard-shortcuts').label,language==='en'?'Keyboard shortcuts':'快捷键速查');
    if (language==='en') assert.equal(await run('/[\\u4e00-\\u9fff]/.test(document.querySelector("#shortcuts-dialog").textContent)'), false);
    for (const theme of ['light','dark','warm']) {
      await run(`document.documentElement.dataset.theme=${JSON.stringify(theme)}`);
      const geometry = await run(`(()=>{const d=document.querySelector('#shortcuts-dialog'),r=d.getBoundingClientRect(),s=document.querySelector('#shortcuts-results'),c=document.querySelector('#shortcuts-close').getBoundingClientRect();return {left:r.left,right:r.right,top:r.top,bottom:r.bottom,width:innerWidth,height:innerHeight,overflow:d.scrollWidth>d.clientWidth,scroll:s.scrollHeight>s.clientHeight,close:c.bottom<=r.bottom,bg:getComputedStyle(d).backgroundColor}})()`);
      assert.ok(geometry.width<=420 && geometry.left>=0 && geometry.right<=geometry.width+1 && geometry.top>=0 && geometry.bottom<=geometry.height+1,JSON.stringify(geometry));
      assert.equal(geometry.overflow,false); assert.equal(geometry.scroll,true); assert.equal(geometry.close,true); colors.add(geometry.bg);
      assert.equal(await run('getComputedStyle(document.documentElement).overflow'), 'hidden', 'only the modal list scrolls, not the background page');
      if (process.env.MDVIEW_SHORTCUT_SCREENSHOTS && language==='en') {
        await run('document.querySelector("#shortcuts-results").scrollTop=0');
        await run('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))');
        fs.writeFileSync(path.join(dir,`shortcuts-${theme}.png`),(await win.webContents.capturePage()).toPNG());
      }
      await run('document.querySelector("#shortcuts-results").scrollTop=10000');
      assert.ok(await run('document.querySelector("#shortcuts-results").scrollTop>0'));
    }
    await run('document.querySelector("#shortcuts-close").click()');
    await wait('!document.querySelector("#shortcuts-dialog").open');
  }
  assert.equal(colors.size,3);
  assert.equal(await run('payload().source'),source);
  win.focus();
  await run('richEditor.editor.view.focus()');
  await wait('window.mdview.getMenuBar().then(data => data.state.shortcutHelpOpen === false)');
  key('F1'); await wait('document.querySelector("#shortcuts-dialog").open');
  win.close();
  await wait('document.querySelector("#unsaved-dialog").open');
  assert.equal(await run('document.querySelector("#shortcuts-dialog").open'),false,'window-close decision supersedes help');
  key('Escape'); await wait('!fileBusy && !document.querySelector("#unsaved-dialog").open');
  assert.equal(await run('payload().source'),source);
  await wait('document.activeElement.matches(".ProseMirror")');
  // Every native accelerator is represented; data is the authority for explicit bindings.
  const { entries } = require('../src/shortcuts-data.js');
  const native = Menu.getApplicationMenu().items.flatMap(section=>section.submenu.items).filter(item=>item.accelerator);
  const normalize = value=>value.replace(/CommandOrControl|CmdOrCtrl/g,'Ctrl').toLowerCase();
  for (const entry of entries.filter(e=>e.accelerator)) assert.ok(native.some(item=>item.accelerator===entry.accelerator), entry.id);
  for (const command of native) assert.ok(entries.some(entry=>entry.keys.some(key=>normalize(key)===normalize(command.accelerator))), command.label);
  if (process.env.MDVIEW_SHORTCUT_SCREENSHOTS) console.log('Shortcut screenshots:',dir);
  console.log('SHORTCUTS PASS: native F1/menu, X/Escape, filter/empty, focus trap/restore, accelerator isolation, unsaved cancel, source/model/selection/history, bilingual labels, 3 themes, 420px geometry, native catalog audit');
  app.exit(0);
})().catch(error => { console.error(error); app.exit(1); });
