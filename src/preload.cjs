const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('mdview', {
  popupTabMenu: request => ipcRenderer.invoke('popup-tab-menu', request),
  tabFileAction: request => ipcRenderer.invoke('tab-file-action', request),
  onRenamed: callback => ipcRenderer.on('renamed', (_event, value) => callback(value)),
  onRenameQuestion: callback => ipcRenderer.on('rename-question', (_event, value) => callback(value)),
  onRenameDismiss: callback => ipcRenderer.on('rename-dismiss', (_event, id) => callback(id)),
  answerRename: (id, name) => ipcRenderer.send('rename-answer', { id, name }),
  onUnsavedConfirm: callback => ipcRenderer.on('unsaved-confirm', (_event, question) => callback(question)),
  onUnsavedConfirmDismiss: callback => ipcRenderer.on('unsaved-confirm-dismiss', (_event, id) => callback(id)),
  answerUnsavedConfirm: (id, choice) => ipcRenderer.send('unsaved-confirm-answer', { id, choice }),
  pasteImage: bytes => ipcRenderer.invoke('paste-image', bytes),
  getLinkIcon: target => ipcRenderer.invoke('link-icon', target),
  getMenuBar: () => ipcRenderer.invoke('get-menu-bar'),
  popupMenu: (index, point) => ipcRenderer.invoke('popup-menu', index, point),
  quickAction: action => ipcRenderer.invoke('quick-action', action),
  setQuickActions: actions => ipcRenderer.invoke('set-quick-actions', actions),
  onQuickActionsChanged: callback => ipcRenderer.on('quick-actions-changed', (_event, actions) => callback(actions)),
  onMenuStateChanged: callback => ipcRenderer.on('menu-state-changed', (_event, state) => callback(state)),
  onActivateMenuBar: callback => ipcRenderer.on('activate-menu-bar', (_event, index) => callback(index)),
  workspaceView: payload => ipcRenderer.send('workspace-view', payload),
  draft: payload => ipcRenderer.send('draft', payload),
  menuState: state => ipcRenderer.send('menu-state', state),
  onMenuAction: callback => ipcRenderer.on('menu-action', (_event, action, value) => callback(action, value)),
  save: payload => ipcRenderer.invoke('save', payload),
  searchDocument: request => ipcRenderer.invoke('search-document', request),
  cancelContentSearch: () => ipcRenderer.send('cancel-content-search'),
  preview: payload => ipcRenderer.invoke('preview', payload),
  onDocumentTimes: callback => ipcRenderer.on('document-times', (_event, value) => callback(value)),
  onSaved: callback => ipcRenderer.on('saved', (_event, value) => callback(value)),
  onBusy: callback => ipcRenderer.on('file-busy', (_event, value) => callback(value)),
  onSaveRequest: callback => ipcRenderer.on('save-request', (_event, value) => callback(value)),
  onToggleEdit: callback => ipcRenderer.on('toggle-edit', () => callback()),
  onEditError: callback => ipcRenderer.on('edit-error', (_event, value) => callback(value)),
  open: () => ipcRenderer.invoke('open'),
  newDocument: () => ipcRenderer.invoke('new-document'),
  switchTab: payload => ipcRenderer.invoke('switch-tab', payload),
  closeTab: payload => ipcRenderer.invoke('close-tab', payload),
  onTabs: callback => ipcRenderer.on('tabs', (_event, value) => callback(value)),
  onCloseTabRequest: callback => ipcRenderer.on('close-tab-request', () => callback()),
  onNextTabRequest: callback => ipcRenderer.on('next-tab-request', () => callback()),
  onPreviousTabRequest: callback => ipcRenderer.on('previous-tab-request', () => callback()),
  setUIZoom: factor => ipcRenderer.invoke('set-ui-zoom', factor),
  getSettings: () => ipcRenderer.invoke('get-settings'),
  getI18n: () => ipcRenderer.invoke('get-i18n'),
  setLanguage: language => ipcRenderer.invoke('set-language', language),
  onLanguageChanged: callback => ipcRenderer.on('language-changed', (_event, language) => callback(language)),
  chooseSaveDirectory: () => ipcRenderer.invoke('choose-save-directory'),
  resetSaveDirectory: () => ipcRenderer.invoke('reset-save-directory'),
  drop: file => ipcRenderer.invoke('drop', webUtils.getPathForFile(file)),
  reload: () => ipcRenderer.invoke('reload-document'),
  external: href => ipcRenderer.invoke('external', href),
  copy: text => ipcRenderer.invoke('copy', text),
  onDocument: callback => ipcRenderer.on('document', (_event, result) => callback(result)),
  onToggleOutline: callback => ipcRenderer.on('toggle-outline', () => callback())
});
